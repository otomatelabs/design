// Builds dist/ from tokens/tokens.json. Zero dependencies: `node scripts/build.mjs`.
//   dist/tokens.css   raw tokens as --ot-* custom properties (dark default, light via [data-theme="light"])
//   dist/legacy.css   aliases with the names used by the current otomatelabs.com styles.css (--color-bg, --space-4…)
//   dist/theme.css    Tailwind v4 @theme + shadcn/ui semantic variables (imports tokens.css)
//   dist/motion.js    Motion (framer-motion) presets; motion.d.ts alongside
//   dist/tokens.json  copy of the source tokens
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const t = JSON.parse(readFileSync(join(root, 'tokens/tokens.json'), 'utf8'));
const dist = join(root, 'dist');
mkdirSync(dist, { recursive: true });

const header = '/* Generated by scripts/build.mjs from tokens/tokens.json. Do not edit. */\n';
const decl = (obj, prefix, indent = '  ') =>
  Object.entries(obj).map(([k, v]) => `${indent}--${prefix}${k}: ${v};`).join('\n');

// Semantic layer (shadcn/ui names). Re-declared under [data-theme] so it re-resolves on nested theme scopes.
const semantic = {
  dark: {
    background: 'var(--ot-bg)',
    foreground: 'var(--ot-text-primary)',
    card: 'var(--ot-surface)',
    'card-foreground': 'var(--ot-text-primary)',
    popover: 'var(--ot-surface-raised)',
    'popover-foreground': 'var(--ot-text-primary)',
    primary: 'var(--ot-brand-coral)',
    'primary-foreground': 'var(--ot-bg)',
    secondary: 'var(--ot-surface-raised)',
    'secondary-foreground': 'var(--ot-text-primary)',
    muted: 'var(--ot-bg-elevated)',
    'muted-foreground': 'var(--ot-text-secondary)',
    accent: 'var(--ot-surface-hover)',
    'accent-foreground': 'var(--ot-text-primary)',
    destructive: 'var(--ot-danger)',
    border: 'var(--ot-border-subtle)',
    input: 'var(--ot-border)',
    ring: 'var(--ot-brand-coral)',
    'product-accent': 'var(--ot-brand-coral)',
    'chart-1': 'var(--ot-brand-coral)',
    'chart-2': 'var(--ot-info)',
    'chart-3': 'var(--ot-success)',
    'chart-4': 'var(--ot-warning)',
    'chart-5': 'var(--ot-brand-violet)',
  },
};
// Light: primary flips to brand-warm with light text (6.58:1); coral with dark text is the dark-mode choice (7.69:1).
semantic.light = { ...semantic.dark, primary: 'var(--ot-brand-warm)', 'primary-foreground': 'var(--ot-bg)', ring: 'var(--ot-brand-warm)' };

const radius = { ...t.radius };

const tokensCss = `${header}
:root,
[data-theme="dark"] {
  color-scheme: dark;
${decl(t.color.dark, 'ot-')}
}

[data-theme="light"] {
  color-scheme: light;
${decl(t.color.light, 'ot-')}
}

:root {
  --ot-font-display: ${t.font.display};
  --ot-font-body: ${t.font.body};
  --ot-font-mono: ${t.font.mono};
${decl(t.text.desktop, 'ot-text-')}
${decl(t.space, 'ot-space-')}
${decl(radius, 'ot-radius-')}
${decl(t.layout, 'ot-')}
${decl(t.motion, 'ot-')}
}

@media (max-width: ${t.text['mobile-breakpoint']}) {
  :root {
${decl(t.text.mobile, 'ot-text-', '    ')}
  }
}

@media (prefers-reduced-motion: reduce) {
  :root {
    --ot-duration-fast: 0ms;
    --ot-duration-base: 0ms;
    --ot-duration-reveal: 0ms;
    --ot-duration-counter: 0ms;
    --ot-stagger: 0ms;
    --ot-reveal-distance: 0px;
  }
}

:root,
[data-theme="dark"] {
${decl(semantic.dark, '')}
  --radius: var(--ot-radius-lg);
}

[data-theme="light"] {
${decl(semantic.light, '')}
}
`;

// Aliases matching the current styles.css of otomatelabs.com, so the site can adopt the package with no renames.
const legacyNames = Object.keys(t.color.dark).filter((k) => !/^(success|warning|danger|info)/.test(k) && k !== 'divider');
const legacyCss = `${header}@import "./tokens.css";

:root,
[data-theme] {
${legacyNames.map((k) => `  --color-${k}: var(--ot-${k});`).join('\n')}
  --color-brand: var(--ot-brand-warm);
  --divider: 1px solid var(--ot-divider);
}

:root {
  --font-display: var(--ot-font-display);
  --font-body: var(--ot-font-body);
${Object.keys(t.text.desktop).map((k) => `  --text-${k}: var(--ot-text-${k});`).join('\n')}
${Object.keys(t.space).map((k) => `  --space-${k}: var(--ot-space-${k});`).join('\n')}
${['sm', 'md', 'lg', 'pill'].map((k) => `  --radius-${k}: var(--ot-radius-${k});`).join('\n')}
  --max-width: var(--ot-max-width);
}
`;

// Tailwind v4. Static values are written literally (no self-referencing vars); theme-dependent colors use `inline`.
const lineHeights = { display: '1.1', h1: '1.15', h2: '1.2', h3: '1.3', h4: '1.4', body: '1.6', 'body-sm': '1.6', caption: '1.5' };
const themeCss = `${header}@import "./tokens.css";

@theme {
  --font-display: ${t.font.display};
  --font-body: ${t.font.body};
  --font-sans: ${t.font.body};
  --font-mono: ${t.font.mono};
  --spacing: 0.25rem;
${Object.keys(t.text.desktop).map((k) => `  --text-${k}: var(--ot-text-${k});\n  --text-${k}--line-height: ${lineHeights[k]};`).join('\n')}
${Object.entries(radius).map(([k, v]) => `  --radius-${k}: ${v};`).join('\n')}
  --container-content: ${t.layout['max-width']};
  --ease-smooth: ${t.motion['ease-smooth']};
  --ease-counter: ${t.motion['ease-counter']};
}

@theme inline {
${Object.keys(semantic.dark).map((k) => `  --color-${k}: var(--${k});`).join('\n')}
${Object.keys(t.color.dark).map((k) => `  --color-ot-${k}: var(--ot-${k});`).join('\n')}
}

@layer base {
  * { border-color: var(--border); }
  body {
    background-color: var(--background);
    color: var(--foreground);
    font-family: var(--ot-font-body);
  }
  h1, h2, h3, h4 { font-family: var(--ot-font-display); }
  :focus-visible { outline: 2px solid var(--ring); outline-offset: 2px; }
}
`;

// Motion presets. Durations in seconds (Motion's unit); easing as cubic-bezier arrays.
const sec = (ms) => Number.parseInt(ms, 10) / 1000;
const bezier = (s) => s.match(/[\d.]+/g).map(Number);
const motionJs = `// Generated by scripts/build.mjs from tokens/tokens.json. Do not edit.
export const ease = { smooth: ${JSON.stringify(bezier(t.motion['ease-smooth']))}, counter: ${JSON.stringify(bezier(t.motion['ease-counter']))} };
export const duration = { fast: ${sec(t.motion['duration-fast'])}, base: ${sec(t.motion['duration-base'])}, reveal: ${sec(t.motion['duration-reveal'])}, counter: ${sec(t.motion['duration-counter'])} };
export const stagger = ${sec(t.motion.stagger)};
const distance = ${Number.parseInt(t.motion['reveal-distance'], 10)};
const tr = { duration: duration.reveal, ease: ease.smooth };

// Variants for <motion.div variants={...} initial="hidden" whileInView="visible" viewport={viewport}>
export const viewport = { once: true, margin: '0px 0px -60px 0px', amount: 0.1 };
export const fadeUp = { hidden: { opacity: 0, y: distance }, visible: { opacity: 1, y: 0, transition: tr } };
export const fadeUpSmall = { hidden: { opacity: 0, y: distance / 2 }, visible: { opacity: 1, y: 0, transition: tr } };
export const scaleIn = { hidden: { opacity: 0, scale: 0.95 }, visible: { opacity: 1, scale: 1, transition: tr } };
export const slideRight = { hidden: { opacity: 0, x: -30 }, visible: { opacity: 1, x: 0, transition: tr } };
export const staggerContainer = (step = stagger) => ({ hidden: {}, visible: { transition: { staggerChildren: step } } });

// whileHover presets. Only transform/opacity: never animate layout properties.
export const hoverLift = { y: -4, transition: { duration: duration.fast, ease: ease.smooth } };
export const hoverLiftSmall = { y: -2, transition: { duration: duration.fast, ease: ease.smooth } };

// Pass the result of Motion's useReducedMotion() to get instant variants.
export const reduced = (variants, prefersReduced) =>
  prefersReduced
    ? Object.fromEntries(Object.keys(variants).map((k) => [k, { opacity: 1, x: 0, y: 0, scale: 1, transition: { duration: 0 } }]))
    : variants;
`;

const motionDts = `export declare const ease: { smooth: [number, number, number, number]; counter: [number, number, number, number] };
export declare const duration: { fast: number; base: number; reveal: number; counter: number };
export declare const stagger: number;
type Variants = Record<string, Record<string, unknown>>;
export declare const viewport: { once: boolean; margin: string; amount: number };
export declare const fadeUp: Variants;
export declare const fadeUpSmall: Variants;
export declare const scaleIn: Variants;
export declare const slideRight: Variants;
export declare function staggerContainer(step?: number): Variants;
export declare const hoverLift: Record<string, unknown>;
export declare const hoverLiftSmall: Record<string, unknown>;
export declare function reduced(variants: Variants, prefersReduced: boolean | null): Variants;
`;

writeFileSync(join(dist, 'tokens.css'), tokensCss);
writeFileSync(join(dist, 'legacy.css'), legacyCss);
writeFileSync(join(dist, 'theme.css'), themeCss);
writeFileSync(join(dist, 'motion.js'), motionJs);
writeFileSync(join(dist, 'motion.d.ts'), motionDts);
writeFileSync(join(dist, 'tokens.json'), JSON.stringify(t, null, 2) + '\n');
console.log('built dist/: tokens.css legacy.css theme.css motion.js motion.d.ts tokens.json');
